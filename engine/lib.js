// engine/lib.js: small helpers shared by every section and page.

// Make text safe to put inside HTML (stops a stray < or & breaking the page)
const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

// Join only the truthy parts (handy for optional bits of HTML)
const join = (...parts) => parts.flat(Infinity).filter(Boolean).join('');

// Stop a single word sitting alone on the last line: glue the last two words together
const keepEnd = (s) => esc(s).replace(/ (\S+)$/, '&nbsp;$1');

// Money: 55 -> "£55", 12.5 -> "£12.50"
const money = (n) => (n == null || n === '') ? '' :
  '£' + (Number.isInteger(Number(n)) ? Number(n) : Number(n).toFixed(2));

// UK phone helpers: '07700 900123' -> '+447700900123' (tel:) / '447700900123' (WhatsApp)
const digits = (s) => String(s || '').replace(/[^\d+]/g, '');
const ukIntl = (s) => {
  const d = digits(s);
  if (d.startsWith('+44')) return d.slice(1);
  if (d.startsWith('44')) return d;
  if (d.startsWith('0')) return '44' + d.slice(1);
  return d;
};
const telHref = (s) => 'tel:+' + ukIntl(s);
const waHref = (s, msg) => 'https://wa.me/' + ukIntl(s) + (msg ? '?text=' + encodeURIComponent(msg) : '');
const mailHref = (addr, subject) => 'mailto:' + addr + (subject ? '?subject=' + encodeURIComponent(subject) : '');

// Days for opening hours: 'Mo-Fr' -> ['Mo','Tu','We','Th','Fr']; 'Sa,Su' -> ['Sa','Su']
const DAY_CODES = ['Mo', 'Tu', 'We', 'Th', 'Fr', 'Sa', 'Su'];
const DAY_NAMES = { Mo: 'Monday', Tu: 'Tuesday', We: 'Wednesday', Th: 'Thursday', Fr: 'Friday', Sa: 'Saturday', Su: 'Sunday' };
const SCHEMA_DAYS = { Mo: 'Monday', Tu: 'Tuesday', We: 'Wednesday', Th: 'Thursday', Fr: 'Friday', Sa: 'Saturday', Su: 'Sunday' };
function parseDays(spec) {
  const out = [];
  for (const part of String(spec || '').split(',').map(s => s.trim()).filter(Boolean)) {
    const [a, b] = part.split('-').map(s => s.trim());
    const ia = DAY_CODES.indexOf(a), ib = b ? DAY_CODES.indexOf(b) : ia;
    if (ia < 0 || ib < 0) return null;
    for (let i = ia; ; i = (i + 1) % 7) { out.push(DAY_CODES[i]); if (i === ib) break; }
  }
  return out.length ? out : null;
}
function daysLabel(spec) {
  const days = parseDays(spec) || [];
  if (days.length === 1) return DAY_NAMES[days[0]];
  const consecutive = days.every((d, i) => i === 0 || (DAY_CODES.indexOf(days[i - 1]) + 1) % 7 === DAY_CODES.indexOf(d));
  if (consecutive && days.length > 2) return `${DAY_NAMES[days[0]]} to ${DAY_NAMES[days[days.length - 1]]}`;
  return days.map(d => DAY_NAMES[d]).join(', ').replace(/, ([^,]*)$/, ' and $1');
}
// '09:00' -> '9am', '17:30' -> '5.30pm' (British style)
function time12(t) {
  const [h, m] = String(t).split(':').map(Number);
  const suffix = h >= 12 ? 'pm' : 'am';
  const h12 = h % 12 === 0 ? 12 : h % 12;
  if (h === 12 && m === 0) return 'midday';
  return h12 + (m ? '.' + String(m).padStart(2, '0') : '') + suffix;
}

